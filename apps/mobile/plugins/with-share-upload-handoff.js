const { withAppDelegate } = require('expo/config-plugins')

const marker = '// @generated by with-share-upload-handoff'

function replaceRequired(contents, search, replacement, label) {
  if (!contents.includes(search)) {
    throw new Error(`Unable to configure ${label} in the generated iOS AppDelegate.`)
  }
  return contents.replace(search, replacement)
}

function transformAppDelegate(source) {
  const existingHandoffCount = source.match(/ShareUploadHandoff\.handle\(url\)/g)?.length ?? 0
  const alreadyConfigured
    = source.includes('import PhotoMasonry\n')
      && source.includes('var sanitizedLaunchOptions = launchOptions')
      && existingHandoffCount === 2
  if (source.includes(marker) || alreadyConfigured) {
    return source
  }

  let contents = source
  if (!contents.includes('internal import PhotoMasonry\n')) {
    if (contents.includes('internal import Expo\n')) {
      contents = contents.replace('internal import Expo\n', 'internal import Expo\ninternal import PhotoMasonry\n')
    }
    else {
      contents = replaceRequired(contents, 'import Expo\n', 'import Expo\nimport PhotoMasonry\n', 'PhotoMasonry import')
    }
  }

  contents = replaceRequired(
    contents,
    '  ) -> Bool {\n    let delegate = ReactNativeDelegate()',
    `  ) -> Bool {
    ${marker}
    var sanitizedLaunchOptions = launchOptions
    if let url = launchOptions?[.url] as? URL,
       ShareUploadHandoff.handle(url) {
      sanitizedLaunchOptions?.removeValue(forKey: .url)
    }

    let delegate = ReactNativeDelegate()`,
    'cold-launch Share Upload handoff',
  )
  contents = replaceRequired(
    contents,
    '      launchOptions: launchOptions)',
    '      launchOptions: sanitizedLaunchOptions)',
    'React Native launch options',
  )
  contents = replaceRequired(
    contents,
    '    return super.application(application, didFinishLaunchingWithOptions: launchOptions)',
    '    return super.application(application, didFinishLaunchingWithOptions: sanitizedLaunchOptions)',
    'Expo launch options',
  )
  contents = replaceRequired(
    contents,
    '  ) -> Bool {\n    return super.application(app, open: url, options: options)',
    `  ) -> Bool {
    if ShareUploadHandoff.handle(url) {
      return true
    }
    return super.application(app, open: url, options: options)`,
    'warm-launch Share Upload handoff',
  )
  return contents
}

module.exports = function withShareUploadHandoff(config) {
  return withAppDelegate(config, (appDelegateConfig) => {
    if (appDelegateConfig.modResults.language !== 'swift') {
      throw new Error('Share Upload handoff requires a Swift iOS AppDelegate.')
    }
    appDelegateConfig.modResults.contents = transformAppDelegate(appDelegateConfig.modResults.contents)
    return appDelegateConfig
  })
}

module.exports.transformAppDelegate = transformAppDelegate
